/**
 * Writes public/robots.txt and public/sitemap.xml from VITE_SITE_URL.
 *
 * Runs as `prebuild` so the deployed files always carry the real domain instead
 * of a hard-coded one that silently rots. Both files are generated — edit this
 * script, not the output.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = path.join(ROOT, "public");

/** Reads VITE_SITE_URL from the environment or the .env files, in Vite's order. */
const readSiteUrl = () => {
  if (process.env.VITE_SITE_URL) return process.env.VITE_SITE_URL;

  for (const file of [".env.production", ".env.local", ".env"]) {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) continue;

    const match = fs
      .readFileSync(full, "utf8")
      .match(/^\s*VITE_SITE_URL\s*=\s*(.+)$/m);

    if (match) return match[1].trim().replace(/^["']|["']$/g, "");
  }

  return "";
};

const siteUrl = readSiteUrl().trim().replace(/\/$/, "");

if (!siteUrl) {
  console.warn(
    "[seo] VITE_SITE_URL is not set — skipping robots.txt/sitemap.xml.\n" +
      "      Set it in frontend/.env to your production origin, e.g.\n" +
      "      VITE_SITE_URL=https://huntintown.com",
  );
  process.exit(0);
}

/**
 * Public, indexable routes. Everything else is either auth-gated or per-user.
 * Keep in sync with NOINDEX_PREFIXES in src/shared/lib/seo.ts.
 */
const PUBLIC_ROUTES = [
  { path: "/", changefreq: "daily", priority: "1.0" },
  { path: "/explore", changefreq: "hourly", priority: "0.9" },
  { path: "/about", changefreq: "monthly", priority: "0.5" },
];

const DISALLOWED = [
  "/dashboard",
  "/messaging",
  "/activity",
  "/responses",
  "/create-post",
  "/profile",
  "/login",
];

const today = new Date().toISOString().slice(0, 10);

const robots = `# Generated by scripts/generate-seo-files.mjs — do not edit by hand.
User-agent: *
${DISALLOWED.map((route) => `Disallow: ${route}`).join("\n")}
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`;

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PUBLIC_ROUTES.map(
  ({ path: route, changefreq, priority }) => `  <url>
    <loc>${siteUrl}${route}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`,
).join("\n")}
</urlset>
`;

fs.mkdirSync(PUBLIC_DIR, { recursive: true });
fs.writeFileSync(path.join(PUBLIC_DIR, "robots.txt"), robots);
fs.writeFileSync(path.join(PUBLIC_DIR, "sitemap.xml"), sitemap);

console.log(`[seo] wrote robots.txt and sitemap.xml for ${siteUrl}`);
